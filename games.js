export const galleryImages = games.flatMap((g) =>
  g.galleryImages.map((src) => ({ src, game: g.id, title: g.title }))
);

// All unique features across all games
export const allFeatures = [...new Set(
  games.flatMap(g => g.features.map(f => f.name))
)].sort();

export function getGame(id) {
  return games.find((g) => g.id === id) || games[0];
}

// Get games that have a specific feature
export function getGamesByFeature(featureName) {
  return games.filter(g => g.features.some(f => f.name === featureName));
}